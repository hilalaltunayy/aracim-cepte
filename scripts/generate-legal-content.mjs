import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { format, resolveConfig } from 'prettier';

const repositoryRoot = process.cwd();
const outputPath = path.join(
  repositoryRoot,
  'src',
  'features',
  'legal',
  'generatedLegalContent.ts',
);

const sources = [
  {
    id: 'kvkkNotice',
    title: 'KVKK Aydınlatma Metni',
    sourcePath: 'docs/legal/kvkk-aydinlatma-metni.md',
  },
  {
    id: 'privacyPolicy',
    title: 'Gizlilik Politikası',
    sourcePath: 'docs/legal/gizlilik-politikasi.md',
  },
  {
    id: 'retentionAndDeletion',
    title: 'Saklama ve Silme Politikası',
    sourcePath: 'docs/legal/saklama-ve-silme-politikasi.md',
  },
  {
    id: 'kvkkApplicationAndAccountDeletion',
    title: 'KVKK Başvuru, Hesap ve Veri Silme',
    sourcePath: 'docs/legal/kvkk-basvuru-ve-hesap-silme.md',
  },
];

function cleanInlineMarkdown(value) {
  return value
    .replace(/^>\s?/, '')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/\[([^\]]+)]\(([^)]+)\)/g, '$1 ($2)')
    .trim();
}

function parseMarkdown(markdown, source) {
  const lines = markdown.replace(/\r\n/g, '\n').split('\n');
  const preamble = [];
  const sections = [];
  let currentSection = null;
  let paragraphLines = [];

  const target = () => currentSection?.paragraphs ?? preamble;
  const flushParagraph = () => {
    if (paragraphLines.length === 0) return;
    target().push(cleanInlineMarkdown(paragraphLines.join(' ')));
    paragraphLines = [];
  };

  for (const originalLine of lines) {
    const line = originalLine.trim();

    if (line.startsWith('# ')) {
      flushParagraph();
      continue;
    }

    if (line.startsWith('## ')) {
      flushParagraph();
      currentSection = { title: cleanInlineMarkdown(line.slice(3)), paragraphs: [] };
      sections.push(currentSection);
      continue;
    }

    if (line.startsWith('### ')) {
      flushParagraph();
      target().push(cleanInlineMarkdown(line.slice(4)));
      continue;
    }

    if (!line) {
      flushParagraph();
      continue;
    }

    if (/^[-*]\s+/.test(line)) {
      flushParagraph();
      target().push(`• ${cleanInlineMarkdown(line.replace(/^[-*]\s+/, ''))}`);
      continue;
    }

    if (line.startsWith('|')) {
      flushParagraph();
      if (!/^\|?[\s:|-]+\|?$/.test(line)) {
        const cells = line
          .split('|')
          .map((cell) => cleanInlineMarkdown(cell))
          .filter(Boolean);
        if (cells.length) target().push(cells.join(' — '));
      }
      continue;
    }

    if (line.startsWith('>')) {
      flushParagraph();
      const quote = cleanInlineMarkdown(line);
      if (quote) target().push(quote);
      continue;
    }

    paragraphLines.push(line);
  }

  flushParagraph();

  return {
    id: source.id,
    title: source.title,
    status: 'HUKUK İNCELEMESİ BEKLİYOR',
    sourcePath: source.sourcePath,
    sections: preamble.length
      ? [{ title: 'Belge durumu', paragraphs: preamble }, ...sections]
      : sections,
  };
}

const documents = {};
for (const source of sources) {
  const markdown = await readFile(path.join(repositoryRoot, source.sourcePath), 'utf8');
  documents[source.id] = parseMarkdown(markdown, source);
}

const rawOutput = `// This file is generated by scripts/generate-legal-content.mjs.\n// Edit docs/legal canonical Markdown files, then regenerate.\n\nexport interface GeneratedLegalSection {\n  title: string;\n  paragraphs: string[];\n}\n\nexport interface GeneratedLegalDocument {\n  id: string;\n  title: string;\n  status: string;\n  sourcePath: string;\n  sections: GeneratedLegalSection[];\n}\n\nexport const generatedLegalDocuments = ${JSON.stringify(documents, null, 2)} as const satisfies Record<string, GeneratedLegalDocument>;\n`;
const prettierConfig = (await resolveConfig(outputPath)) ?? {};
const output = await format(rawOutput, { ...prettierConfig, filepath: outputPath });

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== output) {
    console.error('Generated legal content is stale. Run: node scripts/generate-legal-content.mjs');
    process.exitCode = 1;
  } else {
    console.log('Generated legal content is up to date.');
  }
} else {
  await writeFile(outputPath, output, 'utf8');
  console.log(`Generated ${path.relative(repositoryRoot, outputPath)}.`);
}
